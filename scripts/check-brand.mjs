#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const args = new Set(process.argv.slice(2));
const strict = args.has('--strict');

function read(file) {
  return fs.readFileSync(path.join(root, file), 'utf8');
}

function extractGeneratedBrand() {
  const text = read('src/brand.generated.ts');
  const value = key => text.match(new RegExp(`${key}:\\s*['"]([^'"]+)['"]`))?.[1]
    ?? text.match(new RegExp(`"${key}":\\s*"([^"]+)"`))?.[1]
    ?? '';
  const nestedValue = (objectKey, key) => {
    const objectMatch = text.match(new RegExp(`${objectKey}:\\s*{([\\s\\S]*?)}`))
      ?? text.match(new RegExp(`"${objectKey}":\\s*{([\\s\\S]*?)}`));
    const block = objectMatch?.[1] ?? '';
    return block.match(new RegExp(`${key}:\\s*['"]([^'"]+)['"]`))?.[1]
      ?? block.match(new RegExp(`"${key}":\\s*"([^"]+)"`))?.[1]
      ?? '';
  };
  return {
    appName: value('appName'),
    appSlug: value('appSlug'),
    appId: value('appId'),
    protocol: value('protocol'),
    github: {
      owner: nestedValue('github', 'owner'),
      repo: nestedValue('github', 'repo'),
    },
  };
}

const brand = extractGeneratedBrand();
const isDefaultFerdium = brand.appName === 'Ferdium' || brand.appSlug === 'ferdium';
const failures = [];
const warnings = [];

function fail(message) {
  failures.push(message);
}

function warn(message) {
  warnings.push(message);
}

function assertIncludes(file, needle, label) {
  const text = read(file);
  if (!text.includes(needle)) fail(`${file}: missing ${label}: ${needle}`);
}

function assertNotIncludes(file, needle, label) {
  const text = read(file);
  if (text.includes(needle)) fail(`${file}: still contains ${label}: ${needle}`);
}

// Hard checks: files that should be patched/generated by brand:apply.
assertIncludes('package.json', `"productName": "${brand.appName}"`, 'productName');
assertIncludes('package.json', `"name": "${brand.appSlug}"`, 'package name');
assertIncludes('package.json', `"appId": "${brand.appId}"`, 'appId');
assertIncludes('electron-builder.yml', `appId: "${brand.appId}"`, 'electron appId');
assertIncludes('electron-builder.yml', `name: ${brand.appName}`, 'protocol display name');
assertIncludes('electron-builder.yml', `schemes: [${brand.protocol}]`, 'protocol scheme');
assertIncludes('electron-builder.yml', `executableName: ${brand.appSlug}`, 'Linux executable name');
assertIncludes('src/index.html', `<title>${brand.appName}</title>`, 'HTML title');
assertIncludes('src/dev-app-update.yml', `owner: ${brand.github.owner}`, 'update owner');
assertIncludes('src/dev-app-update.yml', `repo: ${brand.github.repo}`, 'update repo');

if (!isDefaultFerdium) {
  assertNotIncludes('package.json', '"productName": "Ferdium"', 'upstream productName');
  assertNotIncludes('electron-builder.yml', 'schemes: [ferdium]', 'upstream protocol scheme');
  assertNotIncludes('electron-builder.yml', 'executableName: ferdium', 'upstream executable name');
  assertNotIncludes('src/index.html', '<title>Ferdium</title>', 'upstream HTML title');
}

// Soft scan: useful warnings for future migration, but not a build blocker by default.
const scanFiles = [
  'src/components/auth/Welcome.tsx',
  'src/components/auth/ChangeServer.tsx',
  'src/components/settings/supportFerdium/SupportFerdiumDashboard.tsx',
  'src/containers/settings/EditSettingsScreen.tsx',
  'src/internal-server/resources/views/index.edge',
];
const warningPatterns = [/Ferdium/g, /ferdium\.org/g, /github\.com\/ferdium/g];
for (const file of scanFiles) {
  const full = path.join(root, file);
  if (!fs.existsSync(full)) continue;
  const lines = read(file).split(/\r?\n/);
  lines.forEach((line, i) => {
    if (warningPatterns.some(p => p.test(line))) {
      warn(`${file}:${i + 1}: ${line.trim()}`);
    }
    warningPatterns.forEach(p => { p.lastIndex = 0; });
  });
}

if (warnings.length) {
  console.log(`Brand migration warnings (${warnings.length}):`);
  for (const w of warnings.slice(0, 80)) console.log(`WARN ${w}`);
  if (warnings.length > 80) console.log(`WARN ...and ${warnings.length - 80} more`);
}

if (failures.length) {
  console.error(`Brand check failed (${failures.length}):`);
  for (const f of failures) console.error(`FAIL ${f}`);
  process.exit(1);
}

if (strict && !isDefaultFerdium && warnings.length) {
  console.log('Strict mode passed hard checks. Warnings are tracked for gradual migration.');
}

console.log(`Brand check passed for ${brand.appName} (${brand.appSlug}).`);
